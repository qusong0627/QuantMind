# coding: utf-8
"""Interactive setup: ask a few questions, write the config files.

    bigqmt-init                              # console script
    python -m bigqmt_signal_trader.init_config   # same thing

Getting a working deployment previously meant copying two .example.py files,
knowing which of ~30 keys actually matter, and keeping the server and client
blocks consistent by hand. This asks for the handful that vary and derives the
rest.

Writes up to three things:

  * bigqmt_signal_trader_local_config.py   -- QMT-side (the python directory)
  * bigqmt_signal_trader_client_config.py  -- client-side
  * a single-file build with the config baked in, for sandboxes that allow
    neither external imports nor file loading (issue #56)

On passwords: the Redis password is a service credential and goes in the config
file, which is what the .example.py files already document. The QMT *login*
password is not stored -- qmt_launcher reads it from BIGQMT_LOGIN_PASSWORD so it
never reaches argv or a file on disk, and this tool keeps that arrangement.
"""

