def _zmq_default_port(account_id):
    """The zmq transport derives its port from the account id when no explicit
    address is configured; mirror that so the client block points somewhere
    real instead of a placeholder."""
    # Keep one source of truth for the derivation.  Duplicating the constants
    # here previously made bigqmt-init generate a client address in the 15000
    # range while the QMT-side ZmqTransport listened in the 15560 range.
    from .transports.zmq_transport import _default_zmq_port

    return _default_zmq_port(account_id)


def _zmq_server_bind_host(client_host):
    """Bind loopback for same-host clients, wildcard for a remote QMT host.

    ``client_host`` is the address the external program uses to reach the QMT
    machine.  A server cannot bind that public/DNS name reliably, so a remote
    deployment listens on all local interfaces and leaves interface/firewall
    restriction to the operator.
    """
    normalized = str(client_host or "").strip().lower()
    if normalized in ("", "127.0.0.1", "localhost"):
        from .transports.zmq_transport import DEFAULT_ZMQ_HOST

        return DEFAULT_ZMQ_HOST
    return "0.0.0.0"


def _background_threads_for(transport):
    """Which rpc_background_threads value this transport wants.

    Not a safety choice -- trade-context methods are excluded from listener
    processing no matter what this says (#244) -- purely latency. Measured on
    the live terminal over 100 read methods (docs/LATENCY_REPORT.md):

        redis  True 3.4ms   / False 30.7ms
        zmq    True 592.9ms / False 15.8ms
        pipe   True 189.0ms / False 94.4ms

    redis is the only one that wants True: its brpop wake is immediate, while
    zmq/pipe background threads pay a cross-thread GIL handoff (~1 adjust
    tick) on every round trip. One blanket value here is what shipped zmq
    configs 37x slower than they needed to be.
    """
    return str(transport or "redis").lower() in ("redis", "", "default")


def render_server_config(answers):
    """bigqmt_signal_trader_local_config.py -- read by the QMT-side strategy."""
    lines = [
        "# coding: utf-8",
        '"""Local private config for the QMT python directory.',
        "",
        "Generated by `bigqmt-init`.",
        "DO NOT COMMIT: this file holds an account id and Redis credentials.",
        '"""',
        "",
        "BIGQMT_ACCOUNT_ID = %r" % str(answers["account_id"]),
        "",
        "BIGQMT_ACCOUNT_TYPE = %r" % str(answers["account_type"]),
        "",
        "BIGQMT_REDIS_CONFIG = {",
        '    "transport": %r,' % str(answers["transport"]),
        '    "host": %r,' % str(answers["host"]),
        '    "port": %d,' % int(answers["port"]),
        '    "db": %d,' % int(answers["db"]),
        '    "username": %r,' % str(answers["username"]),
        '    "password": %r,' % str(answers["password"]),
    ]
    if str(answers["transport"]) == "zmq":
        port = _zmq_default_port(answers["account_id"])
        bind_host = _zmq_server_bind_host(answers["host"])
        lines.extend([
            "    # Same-host ZMQ stays on loopback. A remote QMT address makes the",
            "    # server bind all interfaces; restrict that port with a firewall.",
            '    "zmq": {"bind_address": "tcp://%s:%d"},' % (bind_host, port),
        ])
    if answers["allow_order_methods"]:
        lines.append("    # Remote order/cancel is ON. Turn it off if you only need queries.")
    else:
        lines.append("    # Remote order/cancel stays off until you explicitly want it.")
    lines.extend([
        '    "rpc_allow_order_methods": %r,' % bool(answers["allow_order_methods"]),
        "    # get_trade_detail_data returns EMPTY off the main strategy thread, so",
        "    # order/query methods always run on QMT's adjust callback -- enforced",
        "    # in code, not by the flag below (#244). rpc_background_threads is a",
        "    # latency choice and it differs per transport: redis wants True,",
        "    # zmq/pipe want False (adjust drain).",
        '    "rpc_process_in_listener": True,',
        '    "rpc_listener_methods": ("*",),',
        '    "rpc_background_threads": %r,' % _background_threads_for(answers["transport"]),
        '    "schedule_adjust": True,',
        '    "schedule_adjust_interval": "100nMilliSecond",',
        '    "full_tick_cache_enabled": False,',
        '    "full_tick_demand_ttl_seconds": 10,',
        '    "full_tick_cache_ttl_seconds": 10,',
        '    "full_tick_refresh_interval_seconds": 0.5,',
        '    "full_tick_market_refresh_interval_seconds": 3,',
        '    "full_tick_refresh_max_wall_seconds": 0.3,',
        '    "full_tick_max_requests": 8,',
        '    "download_jobs_enabled": False,',
        '    "download_job_chunk_size": 10,',
        '    "download_job_max_wall_seconds": 0.5,',
        '    "download_job_ttl_seconds": 3600,',
        '    "exec_events_enabled": True,',
        '    "exec_events_debug_raw_fields": False,',
        "}",
        "",
    ])
    return "\n".join(lines)


